// ---------- chat ----------

function addMessage(role, html) {
  els.welcome.hidden = true;
  const wrap = document.createElement("div");
  wrap.className = `msg ${role}`;
  wrap.innerHTML = html;
  els.messages.appendChild(wrap);
  els.messages.scrollTop = els.messages.scrollHeight;
  return wrap;
}

/** Escape the answer, then add light formatting: paragraphs, bullets, bold, citation chips. */
function formatAnswer(text, msgId, maxCitation) {
  const inline = (s) =>
    escapeHtml(s)
      .replace(/\*\*(.+?)\*\*/g, "<b>$1</b>")
      .replace(/\[(\d+)\]/g, (m, n) =>
        Number(n) >= 1 && Number(n) <= maxCitation
          ? `<button type="button" class="cite" data-target="src-${msgId}-${n}" title="Show source ${n}">${n}</button>`
          : m);

  return text.trim().split(/\n{2,}/).map((block) => {
    const lines = block.split("\n");
    if (lines.every((l) => /^\s*([-*•]|\d+\.)\s+/.test(l))) {
      return `<ul>${lines.map((l) => `<li>${inline(l.replace(/^\s*([-*•]|\d+\.)\s+/, ""))}</li>`).join("")}</ul>`;
    }
    return `<p>${lines.map(inline).join("<br>")}</p>`;
  }).join("");
}

function sourceHtml(c, msgId) {
  const pct = Math.round(Math.max(0, c.score) * 100);
  return `
    <details class="source${c.cited ? " cited" : ""}" id="src-${msgId}-${c.number}">
      <summary>
        <span class="num">${c.number}</span>
        <span class="where"><b>${escapeHtml(c.filename)}</b> · page ${c.page_number}</span>
        <span class="score" title="Similarity between your question and this passage">${pct}% match</span>
      </summary>
      <div class="body"><p class="excerpt">${escapeHtml(c.text)}</p>
        <a class="open" target="_blank" rel="noopener" href="${fileUrl(c.filename, c.page_number)}">Open page ${c.page_number} ↗</a>
      </div>
    </details>`;
}

function renderSources(container, citations, msgId) {
  if (!citations.length) return;
  const cited = citations.filter((c) => c.cited);
  const primary = cited.length ? cited : [];
  const rest = cited.length ? citations.filter((c) => !c.cited) : citations;

  const box = document.createElement("div");
  box.className = "sources";
  box.innerHTML = `<div class="sources-head">${cited.length ? "Sources" : "Retrieved passages"}</div>` +
    primary.map((c) => sourceHtml(c, msgId)).join("");

  if (rest.length) {
    const more = document.createElement("div");
    more.className = "sources";
    more.hidden = primary.length > 0;
    more.innerHTML = rest.map((c) => sourceHtml(c, msgId)).join("");
    if (primary.length) {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "toggle-more";
      btn.textContent = `Show ${rest.length} other retrieved passage${rest.length === 1 ? "" : "s"}`;
      btn.addEventListener("click", () => {
        more.hidden = !more.hidden;
        btn.textContent = more.hidden ? `Show ${rest.length} other retrieved passage${rest.length === 1 ? "" : "s"}` : "Hide other passages";
      });
      box.appendChild(btn);
    }
    box.appendChild(more);
  }
  container.appendChild(box);
}

// Clicking a [n] chip opens and highlights the matching source card.
els.messages.addEventListener("click", (e) => {
  const chip = e.target.closest(".cite");
  if (!chip) return;
  const card = document.getElementById(chip.dataset.target);
  if (!card) return;
  if (card.parentElement.hidden) card.parentElement.hidden = false;
  card.open = true;
  card.scrollIntoView({ behavior: "smooth", block: "center" });
  card.classList.add("flash");
  setTimeout(() => card.classList.remove("flash"), 1400);
});

async function ask(question) {
  state.busy = true;
  updateAskButton();
  addMessage("user", `<div class="bubble">${escapeHtml(question)}</div>`);
  const pending = addMessage("bot", `<div class="bubble thinking"><span class="dots"><i></i><i></i><i></i></span>Searching your documents…</div>`);
  const msgId = ++state.messageId;

  try {
    const r = await api("/api/ask", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        question,
        top_k: Number(els.topK.value),
        documents: state.selected.size ? [...state.selected] : null,
      }),
    });
    pending.innerHTML = `<div class="bubble">${formatAnswer(r.answer, msgId, r.citations.length)}</div>`;
    if (!r.llm_used && r.citations.length) {
      pending.insertAdjacentHTML("afterbegin", `<div class="notice">Passage mode: add a free GEMINI_API_KEY to .env to get written answers.</div>`);
    }
    renderSources(pending, r.citations, msgId);
  } catch (err) {
    pending.classList.add("error");
    pending.innerHTML = `<div class="bubble">${escapeHtml(err.message)}</div>`;
  } finally {
    state.busy = false;
    updateAskButton();
    els.messages.scrollTop = els.messages.scrollHeight;
  }
}

function updateAskButton() {
  els.askBtn.disabled = state.busy || !els.question.value.trim() || state.documents.length === 0;
}

function autosize() {
  els.question.style.height = "auto";
  els.question.style.height = `${els.question.scrollHeight}px`;
}

els.form.addEventListener("submit", (e) => {
  e.preventDefault();
  const q = els.question.value.trim();
  if (!q || state.busy) return;
  if (!state.documents.length) return toast("Upload a PDF first.");
  els.question.value = "";
  autosize();
  ask(q);
});
els.question.addEventListener("keydown", (e) => {
  if (e.key === "Enter" && !e.shiftKey && !e.isComposing) {
    e.preventDefault();
    els.form.requestSubmit();
  }
});
els.question.addEventListener("input", () => { autosize(); updateAskButton(); });

